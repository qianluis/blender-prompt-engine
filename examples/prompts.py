def run(category="纳米材料", **kwargs):
    """
    批量渲染某一类示例。
    在 Blender 里运行：
        import sys; sys.path.insert(0, r'D:/_blender_lab')
        import examples.examples as ex
        ex.run("纳米材料")
    """
    import b3d
    prompts = ALL.get(category, [])
    print("[examples] 共 %d 条：%s" % (len(prompts), category))
    return b3d.make_batch(prompts, **kwargs)


def listing():
    """打印全部指令"""
    for cat, items in ALL.items():
        print("\n=== %s ===" % cat)
        for i, p in enumerate(items, 1):
            print("  %2d. %s" % (i, p))


if __name__ == "__main__":
    listing()
